-- Задача 1 · Подзадача 1.5 - проверка гипотезы «Чёрная пятница»
-- Гипотеза: всплеск заказов в ноябре 2017 связан с Чёрной пятницей (24.11.2017).
-- Что делает файл: доставленные заказы по дням в ноябре 2017.
-- Результат: 01–23.11 - в среднем ~170 заказов в день; 24.11 - 1 147 (×6,7);
--   25–30.11 - в среднем ~369 в день (×2,2). Гипотеза подтверждается.
--   Средние посчитаны по выгрузке этого запроса в Google Таблицах.
-- Зависит от: 01_0_views.sql
-- =====================================================================

SELECT *
FROM v_delivered_daily
WHERE DAY >= '2017-11-01'
	AND DAY <= '2017-11-30'
ORDER BY DAY;
