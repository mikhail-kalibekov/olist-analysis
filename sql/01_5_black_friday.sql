-- Задача 1. Подзадача 1.5 - проверка гипотезы «Чёрная пятница»: заказы по дням в ноябре 2017
-- Зависит от: 01_0_views.sql
-- Итог (посчитано): обычный день до 24.11 ~170 заказов, 24.11.2017 - 1 147 (x6,7), 25-30.11 ~369/день (x2,2)
-- TODO (ревью): средние «до» и «после» сейчас посчитаны вне файла - добавь сюда запрос, которым их получил

SELECT *
FROM v_delivered_daily
WHERE DAY >= '2017-11-01'
	AND DAY <= '2017-11-30'
ORDER BY DAY;
